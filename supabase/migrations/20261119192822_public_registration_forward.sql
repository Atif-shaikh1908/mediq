create schema if not exists private;
alter schema private owner to postgres;
revoke all on schema private from public, anon, authenticated, service_role;

alter table public.patients alter column created_by drop not null;
alter table public.visits alter column created_by drop not null;
alter table public.queue_records alter column created_by drop not null;

create table private.public_registration_requests (
  idempotency_key uuid primary key,
  request_hash text not null check (request_hash ~ '^[0-9a-f]{64}$'),
  client_fingerprint text not null check (client_fingerprint ~ '^[0-9a-f]{64}$'),
  patient_code text not null,
  token text not null,
  created_at timestamptz not null default now()
);

create index public_registration_requests_fingerprint_created_idx
  on private.public_registration_requests (client_fingerprint, created_at desc);
create index public_registration_requests_created_idx
  on private.public_registration_requests (created_at);

alter table private.public_registration_requests enable row level security;
revoke all on private.public_registration_requests from public, anon, authenticated, service_role;

create table private.public_registration_attempts (
  id bigint generated by default as identity primary key,
  client_fingerprint text not null check (client_fingerprint ~ '^[0-9a-f]{64}$'),
  attempted_at timestamptz not null default now()
);

create index public_registration_attempts_fingerprint_time_idx
  on private.public_registration_attempts (client_fingerprint, attempted_at desc);
create index public_registration_attempts_time_idx
  on private.public_registration_attempts (attempted_at);

alter table private.public_registration_attempts enable row level security;
revoke all on private.public_registration_attempts from public, anon, authenticated, service_role;

create function private.register_patient_core(
  p_full_name text,
  p_age integer,
  p_gender text,
  p_mobile text,
  p_department_id uuid
)
returns table (patient_id uuid, patient_code text, visit_id uuid, queue_record_id uuid, token text)
language plpgsql
security definer
set search_path = pg_catalog, public, private, extensions, pg_temp
as $$
declare
  department_row public.departments%rowtype;
  new_patient_id uuid;
  new_patient_code text;
  new_visit_id uuid;
  next_number integer;
  today_kolkata date := (now() at time zone 'Asia/Kolkata')::date;
  new_token text;
  new_queue_id uuid;
begin
  if p_full_name is null or length(trim(p_full_name)) not between 1 and 120
     or p_age is null or p_age not between 0 and 120
     or p_gender is null or p_gender not in ('Female', 'Male', 'Non-binary', 'Prefer not to say')
     or p_mobile is null or length(trim(p_mobile)) not between 7 and 30
     or p_mobile !~ '^[0-9+(). -]{7,30}$' then
    raise exception 'Patient details are invalid' using errcode = '22023';
  end if;

  select * into department_row
  from public.departments
  where id = p_department_id and active = true;
  if not found then
    raise exception 'Department is unavailable' using errcode = '22023';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended(department_row.id::text || ':' || today_kolkata::text, 0)
  );
  select coalesce(max(q.token_number), 0) + 1 into next_number
  from public.queue_records q
  where q.department_id = department_row.id and q.queue_date = today_kolkata;
  new_token := department_row.code || '-' ||
    lpad(next_number::text, greatest(3, length(next_number::text)), '0');

  insert into public.patients (full_name, age, gender, mobile, created_by)
  values (trim(p_full_name), p_age, p_gender, trim(p_mobile), null)
  returning id, patients.patient_code into new_patient_id, new_patient_code;
  insert into public.visits (patient_id, department_id, created_by)
  values (new_patient_id, department_row.id, null)
  returning id into new_visit_id;
  insert into public.queue_records (
    visit_id, department_id, queue_date, token_number, token, created_by
  ) values (
    new_visit_id, department_row.id, today_kolkata, next_number, new_token, null
  ) returning id into new_queue_id;

  return query select new_patient_id, new_patient_code, new_visit_id, new_queue_id, new_token;
end
$$;

revoke all on function private.register_patient_core(text, integer, text, text, uuid)
  from public, anon, authenticated, service_role;
alter function private.register_patient_core(text, integer, text, text, uuid)
  owner to postgres;

create function public.consume_public_registration_attempt(p_client_fingerprint text)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public, private, pg_temp
as $$
declare
  attempt_count bigint;
begin
  if auth.role() is distinct from 'service_role' then
    raise exception 'Public registration is not available to this role' using errcode = 'PT403';
  end if;
  if p_client_fingerprint is null or p_client_fingerprint !~ '^[0-9a-f]{64}$' then
    raise exception 'Registration request is invalid' using errcode = 'PT400';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended('public-register:attempt:' || p_client_fingerprint, 0)
  );
  delete from private.public_registration_attempts
  where attempted_at < now() - interval '24 hours';

  insert into private.public_registration_attempts (client_fingerprint)
  values (p_client_fingerprint);

  select count(*) into attempt_count
  from private.public_registration_attempts
  where client_fingerprint = p_client_fingerprint
    and attempted_at >= now() - interval '10 minutes';
  if attempt_count > 30 then
    raise exception 'Registration request limit exceeded' using errcode = 'PT429';
  end if;
end
$$;

alter function public.consume_public_registration_attempt(text) owner to postgres;
revoke all on function public.consume_public_registration_attempt(text)
  from public, anon, authenticated, service_role;
grant execute on function public.consume_public_registration_attempt(text)
  to service_role;

create function public.register_public_patient(
  p_idempotency_key uuid,
  p_request_hash text,
  p_client_fingerprint text,
  p_full_name text,
  p_age integer,
  p_gender text,
  p_mobile text,
  p_department_name text
)
returns table (patient_code text, token text)
language plpgsql
security definer
set search_path = pg_catalog, public, private, extensions, pg_temp
as $$
declare
  department_id uuid;
  cached_request private.public_registration_requests%rowtype;
  created_patient record;
  recent_request_count bigint;
begin
  if auth.role() is distinct from 'service_role' then
    raise exception 'Public registration is not available to this role' using errcode = 'PT403';
  end if;
  if p_idempotency_key is null
     or p_request_hash is null or p_request_hash !~ '^[0-9a-f]{64}$'
     or p_client_fingerprint is null or p_client_fingerprint !~ '^[0-9a-f]{64}$'
     or p_full_name is null or length(trim(p_full_name)) not between 1 and 120
     or p_age is null or p_age not between 0 and 120
     or p_gender is null or p_gender not in ('Female', 'Male', 'Non-binary', 'Prefer not to say')
     or p_mobile is null or p_mobile !~ '^\+91[6-9][0-9]{9}$'
     or p_department_name is null
     or p_department_name not in ('General Medicine', 'Emergency', 'Cardiology') then
    raise exception 'Patient details are invalid' using errcode = 'PT400';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended('public-register:request:' || p_idempotency_key::text, 0)
  );

  select * into cached_request
  from private.public_registration_requests
  where idempotency_key = p_idempotency_key;
  if found then
    if cached_request.request_hash is distinct from p_request_hash then
      raise exception 'Submission key was already used' using errcode = 'PT409';
    end if;
    return query select cached_request.patient_code, cached_request.token;
    return;
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended('public-register:rate:' || p_client_fingerprint, 0)
  );
  select count(*) into recent_request_count
  from private.public_registration_requests
  where client_fingerprint = p_client_fingerprint
    and created_at >= now() - interval '10 minutes';
  if recent_request_count >= 30 then
    raise exception 'Registration request limit exceeded' using errcode = 'PT429';
  end if;

  select id into department_id
  from public.departments
  where name = p_department_name and active = true;
  if not found then
    raise exception 'Department is unavailable' using errcode = 'PT400';
  end if;

  select * into created_patient
  from private.register_patient_core(
    p_full_name, p_age, p_gender, p_mobile, department_id
  );

  insert into private.public_registration_requests (
    idempotency_key, request_hash, client_fingerprint, patient_code, token
  ) values (
    p_idempotency_key, p_request_hash, p_client_fingerprint,
    created_patient.patient_code, created_patient.token
  );

  return query select created_patient.patient_code, created_patient.token;
end
$$;

alter function public.register_public_patient(uuid, text, text, text, integer, text, text, text)
  owner to postgres;

revoke all on function public.register_public_patient(uuid, text, text, text, integer, text, text, text)
  from public, anon, authenticated, service_role;
grant execute on function public.register_public_patient(uuid, text, text, text, integer, text, text, text)
  to service_role;

commit;